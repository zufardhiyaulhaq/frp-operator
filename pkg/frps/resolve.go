package frps

import (
	"context"
	"crypto/rand"
	"crypto/tls"
	"encoding/hex"
	"fmt"

	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"

	v1 "github.com/zufardhiyaulhaq/frp-operator/api/v1alpha1"
)

// Credentials are the web server's basic-auth login.
type Credentials struct{ Username, Password string }

// Resolved is a Server with every Secret it references read, ready to build objects from.
type Resolved struct {
	Ports              *Ports
	TOML               string
	Token              string
	NewToken           bool              // generated by this call: no token was stored yet
	ConnectionCA       []byte            // ca.crt of bind.tls.certificate; nil when it has none
	ServerNames        []string          // DNS names of bind.tls.certificate
	Dashboard          *Credentials      // nil when the web server is off
	GeneratedDashboard bool              // Dashboard lives in <server>-dashboard (credentials not set)
	Mounted            map[string][]byte // "<secret>/<key>" → every Secret file mounted into the frps pod
}

// Resolve validates s and reads every Secret it references. An error means the spec cannot be
// applied (InvalidConfig). Resolve writes nothing.
func Resolve(ctx context.Context, c client.Client, s *v1.Server, maxPorts int) (*Resolved, error) {
	ports, err := Validate(&s.Spec, maxPorts)
	if err != nil {
		return nil, err
	}
	r := &Resolved{Ports: ports, Mounted: map[string][]byte{}}
	cfg := Config{Ports: ports}
	if cfg.LogLevel, err = s.Spec.Log.LevelOrDefault(); err != nil {
		return nil, err
	}
	if v := s.Spec.Vhost; v != nil {
		cfg.SubdomainHost = v.SubdomainHost
	}

	if err := r.resolveToken(ctx, c, s); err != nil {
		return nil, err
	}
	cfg.Token = r.Token

	if t := s.Spec.Bind.TLS; t != nil {
		cfg.TLS = &TLSConfig{Force: t.Force == nil || *t.Force}
		if t.Certificate != nil {
			name := t.Certificate.Secret.Name
			crt, key, data, err := r.certificate(ctx, c, s.Namespace, name)
			if err != nil {
				return nil, fmt.Errorf("bind.tls.certificate: %w", err)
			}
			if r.ServerNames, err = ServerNames(crt, key); err != nil {
				return nil, fmt.Errorf("bind.tls.certificate %s/%s: %w", s.Namespace, name, err)
			}
			r.ConnectionCA = data["ca.crt"]
			cfg.TLS.CertFile, cfg.TLS.KeyFile = TLSDir+"/tls.crt", TLSDir+"/tls.key"
		}
		if t.ClientCA != nil {
			name := t.ClientCA.Secret.Name
			data, err := getSecret(ctx, c, s.Namespace, name)
			if err != nil {
				return nil, fmt.Errorf("bind.tls.clientCA: %w", err)
			}
			ca, err := need(data, s.Namespace, name, "ca.crt")
			if err != nil {
				return nil, fmt.Errorf("bind.tls.clientCA: %w", err)
			}
			r.Mounted[name+"/ca.crt"] = ca
			cfg.TLS.TrustedCAFile = TLSDir + "/ca.crt"
		}
	}

	if ports.WebServer {
		if cfg.WebServer, err = r.resolveWebServer(ctx, c, s); err != nil {
			return nil, err
		}
	}

	if r.TOML, err = Render(cfg); err != nil {
		return nil, err
	}
	return r, nil
}

func (r *Resolved) resolveToken(ctx context.Context, c client.Client, s *v1.Server) error {
	if a := s.Spec.Authentication; a != nil && a.Token != nil {
		ref := a.Token.Secret
		data, err := getSecret(ctx, c, s.Namespace, ref.Name)
		if err != nil {
			return fmt.Errorf("authentication.token: %w", err)
		}
		v, err := need(data, s.Namespace, ref.Name, ref.Key)
		if err != nil {
			return fmt.Errorf("authentication.token: %w", err)
		}
		if len(v) == 0 {
			return fmt.Errorf("authentication.token: key %q in secret %s/%s is empty", ref.Key, s.Namespace, ref.Name)
		}
		r.Token = string(v)
		return nil
	}
	stored, err := getOptionalSecret(ctx, c, s.Namespace, ConnectionSecretName(s))
	if err != nil {
		return err
	}
	if token := stored["token"]; len(token) > 0 {
		r.Token = string(token)
		return nil
	}
	r.Token, r.NewToken = randomHex(32), true
	return nil
}

func (r *Resolved) resolveWebServer(ctx context.Context, c client.Client, s *v1.Server) (*WebServerConfig, error) {
	web := &WebServerConfig{Port: WebServerPort, Prometheus: s.Spec.Metrics != nil && s.Spec.Metrics.Enabled}
	d := s.Spec.Dashboard
	if d != nil && d.Credentials != nil {
		name := d.Credentials.Secret.Name
		data, err := getSecret(ctx, c, s.Namespace, name)
		if err != nil {
			return nil, fmt.Errorf("dashboard.credentials: %w", err)
		}
		user, err := need(data, s.Namespace, name, "username")
		if err != nil {
			return nil, fmt.Errorf("dashboard.credentials: %w", err)
		}
		password, err := need(data, s.Namespace, name, "password")
		if err != nil {
			return nil, fmt.Errorf("dashboard.credentials: %w", err)
		}
		r.Dashboard = &Credentials{Username: string(user), Password: string(password)}
	} else {
		r.GeneratedDashboard = true
		stored, err := getOptionalSecret(ctx, c, s.Namespace, DashboardSecretName(s))
		if err != nil {
			return nil, err
		}
		if len(stored["username"]) > 0 && len(stored["password"]) > 0 {
			r.Dashboard = &Credentials{Username: string(stored["username"]), Password: string(stored["password"])}
		} else {
			r.Dashboard = &Credentials{Username: "admin", Password: randomHex(16)}
		}
	}
	web.User, web.Password = r.Dashboard.Username, r.Dashboard.Password

	if d != nil && d.TLS != nil {
		name := d.TLS.Certificate.Secret.Name
		crt, key, _, err := r.certificate(ctx, c, s.Namespace, name)
		if err != nil {
			return nil, fmt.Errorf("dashboard.tls.certificate: %w", err)
		}
		if _, err := tls.X509KeyPair(crt, key); err != nil {
			return nil, fmt.Errorf("dashboard.tls.certificate %s/%s: %w", s.Namespace, name, err)
		}
		web.CertFile, web.KeyFile = DashboardTLSDir+"/tls.crt", DashboardTLSDir+"/tls.key"
	}
	return web, nil
}

// certificate reads tls.crt and tls.key from a Secret and records both as mounted.
func (r *Resolved) certificate(ctx context.Context, c client.Client, namespace, name string) (crt, key []byte, data map[string][]byte, err error) {
	if data, err = getSecret(ctx, c, namespace, name); err != nil {
		return nil, nil, nil, err
	}
	if crt, err = need(data, namespace, name, "tls.crt"); err != nil {
		return nil, nil, nil, err
	}
	if key, err = need(data, namespace, name, "tls.key"); err != nil {
		return nil, nil, nil, err
	}
	r.Mounted[name+"/tls.crt"], r.Mounted[name+"/tls.key"] = crt, key
	return crt, key, data, nil
}

func getSecret(ctx context.Context, c client.Client, namespace, name string) (map[string][]byte, error) {
	s := &corev1.Secret{}
	if err := c.Get(ctx, types.NamespacedName{Namespace: namespace, Name: name}, s); err != nil {
		return nil, fmt.Errorf("secret %s/%s: %w", namespace, name, err)
	}
	return s.Data, nil
}

// getOptionalSecret is getSecret where a missing Secret is nil data, not an error.
func getOptionalSecret(ctx context.Context, c client.Client, namespace, name string) (map[string][]byte, error) {
	s := &corev1.Secret{}
	if err := c.Get(ctx, types.NamespacedName{Namespace: namespace, Name: name}, s); err != nil {
		if apierrors.IsNotFound(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("secret %s/%s: %w", namespace, name, err)
	}
	return s.Data, nil
}

func need(data map[string][]byte, namespace, name, key string) ([]byte, error) {
	v, ok := data[key]
	if !ok {
		return nil, fmt.Errorf("key %q not found in secret %s/%s", key, namespace, name)
	}
	return v, nil
}

// randomHex returns n random bytes as hex (2n characters).
func randomHex(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(fmt.Sprintf("crypto/rand: %v", err))
	}
	return hex.EncodeToString(b)
}
